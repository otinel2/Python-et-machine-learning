#definir des variables
x = 5
y = 10

# Arithmetique
print(x + y) # Addition
print(x - y) # Soustraction
print(x * y) # Multiplication
print(x / y) # Division
print(x % y) # Modulo

#comparaison
print(x == y) # Egalité
print(x != y) # Inégalité
print(x > y) # Supérieur
print(x < y) # Inférieur
print(x >= y) # Supérieur ou égal
print(x <= y) # Inférieur ou égal

# Logique
print(False & True) # ET
print(False | True) # OU
print(False ^ True) # OU exclusif

